// Bundled English Dictionary for Word Chain Blitz (ENABLE-derived, Public Domain)

class DictionaryManager {
  private wordSet: Set<string> | null = null;
  private isLoading: boolean = false;
  private loadPromise: Promise<boolean> | null = null;

  public async load(): Promise<boolean> {
    if (this.wordSet !== null) return true;
    if (this.loadPromise !== null) return this.loadPromise;

    this.isLoading = true;
    this.loadPromise = (async () => {
      try {
        // Fetch or load the word list
        const response = await fetch('/dictionary.txt');
        if (!response.ok) {
          throw new Error('Dictionary file could not be loaded');
        }
        const text = await response.text();
        const words = text
          .split('\n')
          .map((w) => w.trim().toLowerCase())
          .filter((w) => w.length >= 3 && /^[a-z]+$/.test(w));

        this.wordSet = new Set(words);
        this.isLoading = false;
        return true;
      } catch (err) {
        console.warn('Falling back to built-in lexicon:', err);
        // Fallback to built-in common core words if network fetch fails
        this.wordSet = new Set(FALLBACK_WORDS);
        this.isLoading = false;
        return true;
      }
    })();

    return this.loadPromise;
  }

  public isValid(word: string): boolean {
    if (!this.wordSet) return false;
    const clean = word.trim().toLowerCase();
    return clean.length >= 3 && /^[a-z]+$/.test(clean) && this.wordSet.has(clean);
  }

  public hasLoaded(): boolean {
    return this.wordSet !== null;
  }

  public isBusy(): boolean {
    return this.isLoading;
  }

  public getCount(): number {
    return this.wordSet ? this.wordSet.size : 0;
  }
}

